/// 노트 번호 표시. GM 타악기 범위(35–81)면 이름을 붙인다(`37 · Side Stick`, `60`).
#[must_use]
pub fn percussion_label(note: u8) -> String {
    match note
        .checked_sub(35)
        .and_then(|i| GM_PERCUSSION.get(usize::from(i)))
    {
        Some(name) => format!("{note} · {name}"),
        None => note.to_string(),
    }
}
